const DEFAULT_LANG = 'es';
const SUPPORTED_LANGS = ['es', 'en'];
const STORAGE_KEY = 'portfolio-lang';

let currentLang = DEFAULT_LANG;

/* ---------- 2. Utilidades ---------- */
function resolveKey(source, path) {
  return source[path];
}

function t(key) {
  const value = resolveKey(translations[currentLang], key);
  if (typeof value === 'string') return value;
  const fallback = resolveKey(translations[DEFAULT_LANG], key);
  return typeof fallback === 'string' ? fallback : key;
}

function readSavedLang() {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    return SUPPORTED_LANGS.includes(saved) ? saved : DEFAULT_LANG;
  } catch (error) {
    return DEFAULT_LANG;
  }
}

function saveLang(lang) {
  try {
    window.localStorage.setItem(STORAGE_KEY, lang);
  } catch (error) {
    /* El sitio sigue funcionando si localStorage no está disponible. */
  }
}

/* ---------- 3. Selector de idioma ---------- */
const metaDescription = document.querySelector('meta[name="description"]');
const ogTitle = document.querySelector('meta[property="og:title"]');
const ogDescription = document.querySelector('meta[property="og:description"]');
const ogLocale = document.querySelector('meta[property="og:locale"]');
const ogAlternate = document.querySelector('meta[property="og:locale:alternate"]');
function applyLanguage(lang, persist = true) {
  currentLang = SUPPORTED_LANGS.includes(lang) ? lang : DEFAULT_LANG;
  document.documentElement.lang = currentLang;
  document.title = t('meta.title');

  if (metaDescription) metaDescription.setAttribute('content', t('meta.description'));
  ogTitle.content = t('meta.title');
  ogDescription.content = t('meta.description');
  ogLocale.content = currentLang === 'es' ? 'es_BO' : 'en_US';
  ogAlternate.content = currentLang === 'es' ? 'en_US' : 'es_BO';
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
  });

  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    element.setAttribute('alt', t(element.dataset.i18nAlt));
  });

  document.querySelectorAll('[data-lang]').forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.lang === currentLang));
  });

  updateMenuLabel();
  document.getElementById('copy-status').textContent = '';

  if (persist) saveLang(currentLang);
}

/* ---------- 4. Menú desplegable (una sola navegación) ---------- */
const navToggle = document.getElementById('nav-toggle');
const navLinks = document.getElementById('nav-links');

function isMenuOpen() {
  return !!navLinks && navLinks.classList.contains('is-open');
}

function updateMenuLabel() {
  if (!navToggle) return;
  navToggle.setAttribute(
    'aria-label',
    t(isMenuOpen() ? 'nav.closeMenu' : 'nav.openMenu')
  );
}

function setMenu(open) {
  if (!navLinks || !navToggle) return;
  navLinks.classList.toggle('is-open', open);
  navToggle.setAttribute('aria-expanded', String(open));
  updateMenuLabel();
}

function initMenu() {
  if (!navToggle || !navLinks) return;

  navToggle.addEventListener('click', () => setMenu(!isMenuOpen()));

  navLinks.querySelectorAll('a').forEach((link) => {
    link.addEventListener('click', () => {
      if (!isMenuOpen()) return;
      const section = document.getElementById(link.dataset.nav);
      setMenu(false);
      section?.focus({ preventScroll: true });
    });
  });

  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape' && isMenuOpen()) {
      setMenu(false);
      navToggle.focus();
    }
  });

  document.addEventListener('pointerdown', (event) => {
    if (isMenuOpen() && !event.target.closest('.site-header')) {
      setMenu(false);
    }
  });

  const desktopQuery = window.matchMedia('(min-width: 941px)');
  desktopQuery.addEventListener('change', (event) => {
    if (event.matches) setMenu(false);
  });
  document.documentElement.classList.add('js');
}

/* ---------- 6. Sección activa (scroll spy) ---------- */
function initScrollSpy() {
  const sections = Array.from(document.querySelectorAll('main > section[id]'));
  const links = Array.from(document.querySelectorAll('.nav-link'));
  if (!sections.length || !links.length) return;

  const setActive = (id) => {
    links.forEach((link) => {
      const active = link.dataset.nav === id;
      link.classList.toggle('is-active', active);
      if (active) {
        link.setAttribute('aria-current', 'location');
      } else {
        link.removeAttribute('aria-current');
      }
    });
  };

  let current = '';
  let frame = 0;
  let needsMeasure = true;
  let tops = [];
  let probeOffset = 0;
  let end = 0;
  const canObserve = 'ResizeObserver' in window;

  const update = () => {
    frame = 0;
    const scroll = window.scrollY;
    if (needsMeasure) {
      tops = sections.map((section) => section.getBoundingClientRect().top + scroll);
      probeOffset = window.innerHeight * 0.38;
      end = document.documentElement.scrollHeight - window.innerHeight;
      needsMeasure = false;
    }

    let active = sections[0].id;
    for (let i = 1; i < tops.length && tops[i] <= scroll + probeOffset; i++) {
      active = sections[i].id;
    }
    if (scroll >= end - 4) active = sections[sections.length - 1].id;

    if (active !== current) {
      current = active;
      setActive(active);
    }
  };

  const schedule = () => {
    if (!frame) frame = window.requestAnimationFrame(update);
  };
  const invalidate = () => {
    needsMeasure = true;
    schedule();
  };

  update();
  window.addEventListener('scroll', canObserve ? schedule : invalidate, { passive: true });
  window.addEventListener('resize', invalidate);
  window.addEventListener('load', invalidate);
  if (canObserve) {
    const observer = new ResizeObserver(invalidate);
    observer.observe(document.body);
    sections.forEach((section) => observer.observe(section));
  }
}

/* Observe visible rows. The base styles keep all content visible. */
function initReveal() {
  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches ||
    !('IntersectionObserver' in window)) return;

  const observer = new IntersectionObserver((entries) => {
    for (const entry of entries) {
      if (!entry.isIntersecting) continue;
      entry.target.classList.add('just-revealed');
      observer.unobserve(entry.target);
    }
  }, { threshold: 0.05 });

  document.querySelectorAll('[data-reveal]').forEach((item) => observer.observe(item));
}

function initCopyEmail() {
  const button = document.getElementById('copy-email');
  const address = document.getElementById('contact-email');
  const status = document.getElementById('copy-status');

  button.addEventListener('click', async () => {
    try {
      await navigator.clipboard.writeText(address.textContent.trim());
      status.textContent = t('copy.ok');
    } catch {
      const selection = window.getSelection();
      if (selection) {
        const range = document.createRange();
        range.selectNodeContents(address);
        selection.removeAllRanges();
        selection.addRange(range);
      }
      status.textContent = t('copy.error');
    }
  });
  button.hidden = false;
}

